private void loadProperties() {
        javax.swing.table.DefaultTableModel model = (javax.swing.table.DefaultTableModel) tblProperties.getModel();
        model.setRowCount(0); // Clear existing rows

        // 1. Fetch all properties from the global Singleton repository
        java.util.List<MyLib.Property> propertyList = new java.util.ArrayList<>(MyLib.Data.getInstance().properties.values());

        // 2. Filter by Block (SAFELY)
        String selectedBlockStr = (String) cmbBlock.getSelectedItem(); 
        // Only attempt to parse if the string actually starts with "Block "
        if (selectedBlockStr != null && selectedBlockStr.startsWith("Block ")) {
            try {
                int targetBlock = Integer.parseInt(selectedBlockStr.replace("Block ", ""));
                propertyList.removeIf(p -> p.getBlock() != targetBlock);
            } catch (NumberFormatException e) {
                // Safely ignore if the parse fails
            }
        }

        // 3. Determine Sorting Strategy
        String sortBy = (String) cmbSortBy.getSelectedItem();
        String order = (String) cmbOrder.getSelectedItem();
        
        if (sortBy != null && order != null) {
            java.util.Comparator<MyLib.Property> comparator;

            if (sortBy.equals("Lot Size")) {
                comparator = java.util.Comparator.comparingDouble(MyLib.Property::getLotSize);
            } else {
                comparator = java.util.Comparator.comparingDouble(MyLib.Property::getPrice);
            }

            if (order.equals("Descending")) {
                comparator = comparator.reversed();
            }
            
            // Apply the sort
            propertyList.sort(comparator);
        }

        // 4. Populate the Table
        for (MyLib.Property p : propertyList) {
            // Only display properties that are listed and currently available
            if (p.isListed() && p.getStatus().equals("Available")) {
                model.addRow(new Object[]{
                    p.getId(),
                    p.getLotSize() + " sqm",
                    String.format("PHP %,.2f", p.getPrice()),
                    p.getStatus()
                });
            }
        }
    }

