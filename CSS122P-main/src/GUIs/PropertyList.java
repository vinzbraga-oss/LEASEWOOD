    private void jButton1ActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jButton1ActionPerformed
        // 1. Get the highlighted row index
        int selectedRow = tblProperties.getSelectedRow();
        
        // 2. Prevent crashes if they click the button without selecting a row
        if (selectedRow == -1) {
            javax.swing.JOptionPane.showMessageDialog(this, "Please select a property from the table first.", "No Selection", javax.swing.JOptionPane.WARNING_MESSAGE);
            return;
        }

        // 3. Extract the Property ID from column 0 of the clicked row
        String propertyId = (String) tblProperties.getValueAt(selectedRow, 0);
        
        // 4. Fetch the full Property object from the Singleton data store
        MyLib.Property selectedProperty = MyLib.Data.getInstance().properties.get(propertyId);

        // 5. Launch the details window and inject the property
        new PropertyDetails(selectedProperty).setVisible(true);
        
        // 6. Close the current property list window
        this.dispose();// TODO add your handling code here:
    }//GEN-LAST:event_jButton1ActionPerformed

